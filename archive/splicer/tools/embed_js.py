#!/usr/bin/env python3
"""Bake the Movian JS standard library and the payload bootstrap into a header."""
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[1]
JS = ROOT / "js" / "ecmascript"
OUT = ROOT / "src" / "plugin_embed.h"

FILES = [
    "legacy/api-v1.js",
    "modules/movian/page.js",
    "modules/movian/http.js",
    "modules/movian/html.js",
    "modules/movian/itemhook.js",
    "modules/movian/service.js",
    "modules/movian/settings.js",
    "modules/movian/prop.js",
    "modules/movian/xml.js",
    "modules/movian/store.js",
    "modules/http.js",
    "modules/https.js",
    "modules/fs.js",
    "modules/url.js",
    "modules/querystring.js",
    "modules/websocket.js",
]


def c_string(data: bytes) -> str:
    chunks = []
    buf = []

    def flush() -> None:
        if buf:
            chunks.append('"' + "".join(buf) + '"')
            buf.clear()

    for b in data:
        if b == 0x22:
            buf.append('\\"')
        elif b == 0x5C:
            buf.append("\\\\")
        elif b == 0x0A:
            buf.append("\\n")
        elif b == 0x0D:
            buf.append("\\r")
        elif b == 0x09:
            buf.append("\\t")
        elif 32 <= b < 127:
            buf.append(chr(b))
        else:
            buf.append("\\%03o" % b)
            flush()
            continue
        if len(buf) >= 80:
            flush()
    flush()
    if not chunks:
        return '""'
    return "\n".join(chunks)




def main() -> None:
    blobs = []
    boot = (ROOT / "src" / "plugin_boot.js").read_bytes()
    blobs.append(("boot", boot))
    for rel in FILES:
        blobs.append((rel, (JS / rel).read_bytes()))
    parts = [
        "/* Generated by tools/embed_js.py. Movian modules are GPL-3.0 from andoma/movian. */",
        "#ifndef SPLICER_PLUGIN_EMBED_H",
        "#define SPLICER_PLUGIN_EMBED_H",
        "typedef struct { const char *name; const char *data; int len; } plug_blob_t;",
    ]
    for i, (name, data) in enumerate(blobs):
        parts.append("static const char PLUG_BLOB_%d[] = %s;" % (i, c_string(data)))
    parts.append("static const plug_blob_t PLUG_BLOBS[] = {")
    for i, (name, data) in enumerate(blobs):
        parts.append('\t{"%s", PLUG_BLOB_%d, %d},' % (name.replace("\\", "\\\\"), i, len(data)))
    parts.append("};")
    parts.append("static const int PLUG_BLOB_COUNT = %d;" % len(blobs))
    parts.append("#endif")
    OUT.write_text("\n".join(parts) + "\n")
    print("wrote", OUT, "bytes", OUT.stat().st_size)


if __name__ == "__main__":
    main()
